/**
 * متد امن برای دریافت اطلاعات جیسون از مسیرهای چندگانه با جلوگیری از پرتاب استثنای پارس HTML
 */
export async function safeFetchGovernanceJson<T>(filename: string, fallbackDefault: T): Promise<T> {
  const candidateUrls = [
    `/data/05-energy-committee/${filename}`,
    `data/05-energy-committee/${filename}`
  ];

  for (const url of candidateUrls) {
    try {
      const res = await fetch(url);
      if (!res.ok) continue;

      const text = await res.text();
      const trimmed = text.trim();

      // در صورتی که به هر دلیلی صفحه HTML برگشت داده شده باشد (<!doctype...)، از پارس آن اجتناب می‌کنیم
      if (!trimmed || trimmed.startsWith('<')) {
        continue;
      }

      const parsed = JSON.parse(trimmed) as T;
      if (parsed) {
        return parsed;
      }
    } catch {
      // ادامه به مسیر بعدی در صورت بروز هرگونه خطای شبکه یا پارس
    }
  }

  // اگر هیچ مسیری موفق نشد، داده‌های پیش‌فرض را برگردان
  return fallbackDefault;
}
